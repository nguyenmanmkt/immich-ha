#!/usr/bin/env python3
"""Bundle buildless UI assets into an ESM module. No npm/build dependency."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
values = {"ADMIN_HTML": "index.html", "ADMIN_CSS": "admin.css", "ADMIN_JS": "admin.js", "ADMIN_STATUS_JS": "status-model.mjs"}
output = "// Generated by tools/embed-ui.py. Edit web/ source files instead.\n"
for name, filename in values.items():
    output += "export const " + name + " = " + json.dumps((root / "web" / filename).read_text(encoding="utf-8"), ensure_ascii=False) + ";\n"
(root / "src/admin-ui.mjs").write_text(output, encoding="utf-8", newline="\n")
