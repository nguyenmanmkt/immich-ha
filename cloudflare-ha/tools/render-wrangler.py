#!/usr/bin/env python3
"""Generate Wrangler settings from project.json; contains no secrets."""
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from project_config import load_project, worker_variables


def render(project):
    return {
        "$schema": "node_modules/wrangler/config-schema.json",
        "name": project["workerName"], "main": "src/worker.mjs",
        "compatibility_date": "2026-11-16", "workers_dev": True,
        "vars": worker_variables(project),
        "durable_objects": {"bindings": [{"name": "CONTROLLER", "class_name": "HAController"}]},
        "migrations": [{"tag": "v1", "new_sqlite_classes": ["HAController"]}],
        "triggers": {"crons": ["* * * * *"]}, "observability": {"enabled": True},
    }


if __name__ == "__main__":
    (ROOT / "wrangler.jsonc").write_text(
        "// Generated by tools/render-wrangler.py from project.json. Edit project.json.\n"
        + json.dumps(render(load_project()), indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print("Generated wrangler.jsonc from project.json (no DNS or service changes).")
